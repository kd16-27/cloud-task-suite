// Optional browser verification. Requires Node and Playwright + Chromium.
const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
(async()=>{
 const browser=await chromium.launch({headless:true,...(process.env.BROWSER_PATH?{executablePath:process.env.BROWSER_PATH}:{})});
 const page=await browser.newPage({viewport:{width:1440,height:1100}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://127.0.0.1:8080');
 await page.locator('#auth-form input[name=email]').fill('browser-'+Date.now()+'@example.test');
 await page.locator('#auth-form input[name=password]').fill('Demo-Browser-Test-123!');
 await page.locator('#register').click();
 await page.waitForFunction(()=>document.getElementById('status').textContent.includes('Demo account created'));
 await page.locator('#auth-form button[type=submit]').click();
 await page.waitForFunction(()=>document.getElementById('account-state').textContent.includes('Signed in as'));
 await page.locator('#record-form button').click();
 await page.waitForFunction(()=>document.getElementById('record-list').textContent.includes('Alex Morgan'));
 await page.screenshot({path:'evidence/01-records.png',fullPage:true});
 await page.locator('[data-panel=vault]').click();
 await page.locator('#vault-form button').click();
 await page.waitForFunction(()=>document.getElementById('status').textContent.includes('AES-256-GCM'));
 await page.locator('#vault-search button').click();
 await page.waitForFunction(()=>document.getElementById('vault-list').textContent.includes('Training value'));
 await page.screenshot({path:'evidence/02-vault.png',fullPage:true});
 await page.locator('[data-panel=passes]').click();
 await page.locator('#route-list button').first().click();
 await page.waitForFunction(()=>document.getElementById('pass-list').textContent.includes('active'));
 const code=await page.locator('#pass-list pre').first().textContent();
 await page.locator('#verify-form textarea').fill(code);
 await page.locator('#verify-form button').click();
 await page.waitForFunction(()=>document.getElementById('status').textContent.includes('Valid active pass'));
 await page.screenshot({path:'evidence/03-passes.png',fullPage:true});
 await page.locator('#pass-list button').first().click();
 await page.waitForFunction(()=>document.getElementById('pass-list').textContent.includes('cancelled'));
 await page.locator('[data-panel=chat]').click();
 await page.locator('#chat-form input').fill('How do I recover a lost ticket?');
 await page.locator('#chat-form button').click();
 await page.waitForFunction(()=>document.getElementById('chat-log').textContent.includes('Source: Recover'));
 await page.screenshot({path:'evidence/04-chat.png',fullPage:true});
 await page.setViewportSize({width:390,height:844});
 await page.screenshot({path:'evidence/05-mobile.png',fullPage:true});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),true,'No mobile horizontal overflow');
 assert.deepEqual(errors,[]);
 fs.writeFileSync('evidence/browser-tests.json',JSON.stringify({status:'passed',checks:['register','login','record insert','vault encryption roundtrip','booking','signed pass verification','cancel','chat retrieval','mobile layout width','no uncaught browser errors'],note:'Local Chromium; not a live AWS test'},null,2));
 await browser.close(); console.log('Browser smoke tests passed.');
})().catch(e=>{console.error(e);process.exit(1);});
